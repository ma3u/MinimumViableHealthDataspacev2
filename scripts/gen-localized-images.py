#!/usr/bin/env python3
"""List the translated variants of the documentation's images (ADR-071), so
the docs pages show a screenshot or diagram in the picked language where one
exists and the English one everywhere else.

A variant is found by where it lies, next to or below the English file:

    ui/public/images/guide/<lang>/<file>         for /images/guide/<file>
    ui/public/images/screenshots/<lang>/<file>   for /images/screenshots/<file>
    ui/public/published-docs/<stem>.<lang>.<ext> for /published-docs/<stem>.<ext>

The last form is what scripts/gen-docs-content.py copies from a diagram's
translated variant next to its source, e.g. docs/architecture/img/x.de.svg.
The manifest, ui/src/content/localized-images.json, maps each English public
path to its variants; LocalizedImage (ui/src/components/docs/LocalizedImage.tsx)
reads it. A variant whose English file does not exist is an error: it is
almost always a misspelt name, and nothing would ever show it.

    python3 scripts/gen-localized-images.py          # write the manifest
    python3 scripts/gen-localized-images.py --check  # exit 1 when it is stale

The pre-commit hook `localized-images` runs the check.
"""
import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLIC = "ui/public"
OUT = "ui/src/content/localized-images.json"
LANGS = ["de", "fr", "nl", "es"]  # the picker's languages besides English
FOLDERS = ["images/guide", "images/screenshots"]  # <folder>/<lang>/<file>
SUFFIXED = ["published-docs"]  # <folder>/<stem>.<lang>.<ext>
IMAGE = re.compile(r"\.(png|jpe?g|webp|gif|svg|avif)$", re.I)


def scan():
    images, errors = {}, []

    def add(english, lang, variant):
        if not os.path.isfile(os.path.join(ROOT, PUBLIC, english.lstrip("/"))):
            errors.append(f"{PUBLIC}{variant} has no English original {PUBLIC}{english}")
            return
        images.setdefault(english, {})[lang] = variant

    for folder in FOLDERS:
        for lang in LANGS:
            d = os.path.join(ROOT, PUBLIC, folder, lang)
            if not os.path.isdir(d):
                continue
            for name in sorted(os.listdir(d)):
                if IMAGE.search(name):
                    add(f"/{folder}/{name}", lang, f"/{folder}/{lang}/{name}")
    suffix = re.compile(r"^(.+)\.(" + "|".join(LANGS) + r")(\.[^.]+)$")
    for folder in SUFFIXED:
        d = os.path.join(ROOT, PUBLIC, folder)
        if not os.path.isdir(d):
            continue
        for name in sorted(os.listdir(d)):
            m = suffix.match(name)
            if m and IMAGE.search(name):
                add(f"/{folder}/{m.group(1)}{m.group(3)}", m.group(2), f"/{folder}/{name}")
    ordered = {
        k: {lang: images[k][lang] for lang in LANGS if lang in images[k]}
        for k in sorted(images)
    }
    return {
        "_comment": "Generated by scripts/gen-localized-images.py from the translated variants under "
                    "ui/public (ADR-071). Do not edit by hand.",
        "languages": LANGS,
        "images": ordered,
    }, errors


def main():
    global ROOT
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", help=argparse.SUPPRESS)  # a copy of the repository, for the tests
    args = ap.parse_args()
    if args.root:
        ROOT = os.path.abspath(args.root)
    data, errors = scan()
    for e in errors:
        print(f"gen-localized-images: {e}", file=sys.stderr)
    want = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    out = os.path.join(ROOT, OUT)
    try:
        with open(out, encoding="utf-8") as f:
            have = f.read()
    except OSError:
        have = None
    if want == have:
        return 1 if errors else 0
    if args.check:
        print(f"gen-localized-images: {OUT} is stale: run python3 scripts/gen-localized-images.py", file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write(want)
    print(f"gen-localized-images: wrote {OUT}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
