    const onMove = (e) => {
      ptrType = e.pointerType || "mouse";
      const [x, y] = local(e);
      hoverX = x;
      hoverY = y;
      hoverOn = true;
      if (!down || down.id !== e.pointerId) {
        if (ptrType === "mouse") {
          hov = pickOrgan(x, y);
          canvas.style.cursor = hov ? "pointer" : "grab";
        }
        return;
      }
      const dx = x - down.x,
        dy = y - down.y;
      down.x = x;
      down.y = y;
      down.moved += Math.abs(dx) + Math.abs(dy);
      if (down.moved > 7) {
        if (!dragging) {
          dragging = true;
          try {
            canvas.setPointerCapture(e.pointerId);
          } catch (_) {}
          canvas.style.cursor = "grabbing";
        }
        const now = performance.now();
        yaw += dx * 0.009;
        if (ptrType === "mouse")
          pitchU = clamp(pitchU + dy * 0.005, -0.3, 1.25);
        velYaw = lerp(
          velYaw,
          (dx * 0.009) / Math.max(0.008, (now - down.lt) / 1000),
          0.35,
        );
        down.lt = now;
        lastInteract = tt;
      }
    };
    const onUp = (e) => {
      if (!down || down.id !== e.pointerId) return;
      const [x, y] = local(e);
      if (down.moved <= 7 && performance.now() - down.t < 650) {
        const o = pickOrgan(x, y);
        if (o) select(sel === o ? null : o);
        else {
          tapPulse(x, y);
          sel = null;
        }
      }
      velYaw = clamp(velYaw, -3, 3);
      down = null;
      dragging = false;
      canvas.style.cursor = hov ? "pointer" : "grab";
      if (e.pointerType !== "mouse") hoverOn = false;
    };
    const onCancel = () => {
      down = null;
      dragging = false;
      hoverOn = false;
    };
    const onLeave = (e) => {
      if (e.pointerType === "mouse") {
        hoverOn = false;
        hov = null;
      }
    };
