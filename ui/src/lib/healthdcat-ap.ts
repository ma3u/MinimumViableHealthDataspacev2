/** What a dataset row of /api/catalog carries, for the static fallback. */
export interface CatalogEntry {
  id: string;
  title: string;
  description?: string;
  license?: string;
  conformsTo?: string;
  publisher?: string;
  theme?: string;
  datasetType?: string;
  legalBasis?: string;
  recordCount?: number | null;
}

/**
 * A minimal description built in the page, for the static export, which has
 * no proxy. The live hub hands over the proxy's Release 8 document instead.
 */
export function minimalDescription(d: CatalogEntry): Record<string, unknown> {
  return {
    "@context": {
      dcat: "http://www.w3.org/ns/dcat#",
      dct: "http://purl.org/dc/terms/",
      // The HealthDCAT-AP namespace (Release 8, ADR-063).
      healthdcatap: "http://healthdataportal.eu/ns/health#",
      foaf: "http://xmlns.com/foaf/0.1/",
    },
    "@type": "dcat:Dataset",
    "@id": d.id,
    "dct:title": d.title,
    "dct:description": d.description,
    "dct:license": d.license,
    "dct:conformsTo": d.conformsTo,
    "dct:publisher": d.publisher
      ? { "@type": "foaf:Organization", "foaf:name": d.publisher }
      : undefined,
    "dcat:theme": d.theme,
    "healthdcatap:datasetType": d.datasetType,
    "healthdcatap:legalBasisForAccess": d.legalBasis,
    "healthdcatap:numberOfRecords": d.recordCount,
  };
}

type JsonLdNode = Record<string, unknown>;

const XSD = "http://www.w3.org/2001/XMLSchema#";

/**
 * Write compacted JSON-LD as Turtle. Covers what the proxy's serialiser
 * produces: prefixed keys, @id and @type, typed and language-tagged values,
 * nested named nodes (written as their own subjects) and blank nodes (written
 * inline). A key that is neither prefixed nor a keyword is not a term of the
 * context, so JSON-LD drops it, and so does this.
 */
export function toTurtle(doc: JsonLdNode): string {
  const context = (doc["@context"] ?? {}) as Record<string, string>;
  const subjects = new Map<string, string[]>();

  const iri = (s: string) =>
    `<${s.replace(/[\u0000- <>"{}|^`\\]/g, (c) => encodeURIComponent(c))}>`;
  const term = (t: string) => {
    const i = t.indexOf(":");
    const prefix = i > 0 ? t.slice(0, i) : "";
    if (prefix in context && /^[A-Za-z0-9_.-]*$/.test(t.slice(i + 1))) return t;
    return iri(prefix in context ? context[prefix] + t.slice(i + 1) : t);
  };
  const literal = (s: string) =>
    `"${s
      .replace(/\\/g, "\\\\")
      .replace(/"/g, '\\"')
      .replace(/\n/g, "\\n")
      .replace(/\r/g, "\\r")}"`;
  const isTerm = (k: string) => k.startsWith("@") || k.includes(":");

  function object(v: unknown): string | undefined {
    if (v == null) return undefined;
    if (typeof v === "string") return literal(v);
    if (typeof v === "boolean") return String(v);
    if (typeof v === "number") {
      return Number.isInteger(v)
        ? String(v)
        : `${literal(String(v))}^^${iri(XSD + "double")}`;
    }
    if (typeof v !== "object" || Array.isArray(v)) return undefined;
    const n = v as JsonLdNode;
    if (n["@value"] !== undefined && n["@value"] !== null) {
      const value = literal(String(n["@value"]));
      if (n["@language"]) return `${value}@${String(n["@language"])}`;
      if (n["@type"]) return `${value}^^${term(String(n["@type"]))}`;
      return value;
    }
    if (typeof n["@id"] === "string") {
      subject(n);
      return iri(n["@id"]);
    }
    const props = predicates(n);
    return props.length ? `[ ${props.join(" ; ")} ]` : undefined;
  }

  function predicates(n: JsonLdNode): string[] {
    const out: string[] = [];
    for (const [k, v] of Object.entries(n)) {
      if (k === "@context" || k === "@id" || k === "@graph" || !isTerm(k)) {
        continue;
      }
      if (k.startsWith("@") && k !== "@type") continue;
      const values = (Array.isArray(v) ? v : [v])
        .map((x) =>
          k === "@type"
            ? typeof x === "string"
              ? term(x)
              : undefined
            : object(x),
        )
        .filter((x): x is string => x !== undefined);
      if (values.length) {
        out.push(`${k === "@type" ? "a" : term(k)} ${values.join(", ")}`);
      }
    }
    return out;
  }

  function subject(n: JsonLdNode) {
    const id = iri(String(n["@id"]));
    const lines = subjects.get(id) ?? [];
    if (!subjects.has(id)) subjects.set(id, lines);
    for (const line of predicates(n)) {
      // The same triple twice is one triple; a line with a blank node is a new
      // blank node each time, as it is in the JSON-LD, so it is kept.
      if (line.includes("[") || !lines.includes(line)) lines.push(line);
    }
  }

  const roots = Array.isArray(doc["@graph"])
    ? (doc["@graph"] as JsonLdNode[])
    : [doc];
  for (const root of roots) {
    if (typeof root["@id"] === "string") subject(root);
    else {
      const blank = object(root);
      if (blank) subjects.set(blank, []);
    }
  }

  const prefixes = Object.entries(context)
    .filter(([, ns]) => typeof ns === "string")
    .map(([p, ns]) => `@prefix ${p}: ${iri(ns)} .`);
  const blocks = [...subjects.entries()]
    .filter(([, lines]) => lines.length)
    .map(([id, lines]) => `${id}\n    ${lines.join(" ;\n    ")} .`);
  // A root without @id is written as an anonymous subject.
  const anonymous = [...subjects.entries()]
    .filter(([key, lines]) => !lines.length && key.startsWith("["))
    .map(([key]) => `${key} .`);
  return [prefixes.join("\n"), ...blocks, ...anonymous].join("\n\n") + "\n";
}
